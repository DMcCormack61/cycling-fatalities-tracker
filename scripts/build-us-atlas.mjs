/**
 * Bake a United States atlas (lower 48 + Alaska and Hawaii insets) from the
 * simplified folium us-states GeoJSON. Projection parameters are written into
 * src/lib/us-atlas.ts so crash pins use the same transform as the state shapes.
 *
 * Source GeoJSON (not committed): the ~88KB public us-states file used by folium.
 * Re-run: node scripts/build-us-atlas.mjs /path/to/us-states.json
 */
import { readFileSync, writeFileSync } from "node:fs";

const DEG = Math.PI / 180;
const WIDTH = 1000;
const HEIGHT = 640;

const LOWER_BOX = { x0: 16, y0: 12, x1: 984, y1: 500 };
const AK_BOX = { x0: 18, y0: 478, x1: 250, y1: 624 };
const HI_BOX = { x0: 268, y0: 518, x1: 470, y1: 624 };

function albersSpec(phi1, phi2, phi0, lambda0) {
  const p1 = phi1 * DEG;
  const p2 = phi2 * DEG;
  const n = (Math.sin(p1) + Math.sin(p2)) / 2;
  const c = Math.cos(p1) ** 2 + 2 * n * Math.sin(p1);
  const rho0 = Math.sqrt(c - 2 * n * Math.sin(phi0 * DEG)) / n;
  return { n, c, rho0, lambda0: lambda0 * DEG };
}

function projectRaw(lat, lng, spec) {
  const phi = lat * DEG;
  const lambda = lng * DEG;
  const rho = Math.sqrt(spec.c - 2 * spec.n * Math.sin(phi)) / spec.n;
  const theta = spec.n * (lambda - spec.lambda0);
  return {
    x: rho * Math.sin(theta),
    // North is up in SVG.
    y: -(spec.rho0 - rho * Math.cos(theta)),
  };
}

function boundsOf(points) {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (const p of points) {
    if (p.x < minX) minX = p.x;
    if (p.y < minY) minY = p.y;
    if (p.x > maxX) maxX = p.x;
    if (p.y > maxY) maxY = p.y;
  }
  return { minX, minY, maxX, maxY };
}

function fitOf(points, box) {
  const b = boundsOf(points);
  const sx = (box.x1 - box.x0) / (b.maxX - b.minX);
  const sy = (box.y1 - box.y0) / (b.maxY - b.minY);
  const scale = Math.min(sx, sy);
  const dx = box.x0 + ((box.x1 - box.x0) - (b.maxX - b.minX) * scale) / 2 - b.minX * scale;
  const dy = box.y0 + ((box.y1 - box.y0) - (b.maxY - b.minY) * scale) / 2 - b.minY * scale;
  return { scale, dx, dy };
}

function applyFit(p, fit) {
  return { x: p.x * fit.scale + fit.dx, y: p.y * fit.scale + fit.dy };
}

function ringPoints(ring, spec) {
  return ring.map(([lng, lat]) => projectRaw(lat, lng, spec));
}

function pathFromRings(rings, spec, fit) {
  let d = "";
  for (const ring of rings) {
    const pts = ringPoints(ring, spec).map((p) => applyFit(p, fit));
    if (pts.length === 0) continue;
    d += `M${pts[0].x.toFixed(1)} ${pts[0].y.toFixed(1)}`;
    for (let i = 1; i < pts.length; i += 1) {
      d += `L${pts[i].x.toFixed(1)} ${pts[i].y.toFixed(1)}`;
    }
    d += "Z";
  }
  return d;
}

function polygonsOf(geometry) {
  if (geometry.type === "Polygon") return [geometry.coordinates];
  if (geometry.type === "MultiPolygon") return geometry.coordinates;
  throw new Error(`Unexpected geometry ${geometry.type}`);
}

const geoPath = process.argv[2] ?? "/tmp/us-states.json";
const fc = JSON.parse(readFileSync(geoPath, "utf8"));

const lowerSpec = albersSpec(29.5, 45.5, 37.5, -96);
const akSpec = albersSpec(55, 65, 63, -152);
const hiSpec = albersSpec(18, 22, 20.5, -157.5);

const features = fc.features.map((f) => ({
  name: f.properties.name,
  polygons: polygonsOf(f.geometry),
}));

const lower = features.filter((f) => f.name !== "Alaska" && f.name !== "Hawaii");
const alaska = features.find((f) => f.name === "Alaska");
const hawaii = features.find((f) => f.name === "Hawaii");
if (!alaska || !hawaii) throw new Error("Alaska or Hawaii missing from GeoJSON");

const lowerSamples = lower.flatMap((f) =>
  f.polygons.flatMap((poly) => ringPoints(poly[0], lowerSpec)),
);
const akSamples = alaska.polygons.flatMap((poly) => ringPoints(poly[0], akSpec));
const hiSamples = hawaii.polygons.flatMap((poly) => ringPoints(poly[0], hiSpec));

const lowerFit = fitOf(lowerSamples, LOWER_BOX);
const akFit = fitOf(akSamples, AK_BOX);
const hiFit = fitOf(hiSamples, HI_BOX);

const shapes = [
  ...lower.map((f) => ({
    name: f.name,
    d: f.polygons.map((poly) => pathFromRings(poly, lowerSpec, lowerFit)).join(""),
  })),
  {
    name: alaska.name,
    d: alaska.polygons.map((poly) => pathFromRings(poly, akSpec, akFit)).join(""),
  },
  {
    name: hawaii.name,
    d: hawaii.polygons.map((poly) => pathFromRings(poly, hiSpec, hiFit)).join(""),
  },
];

function num(n) {
  return Number(n.toFixed(6));
}

const specLiteral = (spec, fit) => `{
    n: ${num(spec.n)},
    c: ${num(spec.c)},
    rho0: ${num(spec.rho0)},
    lambda0: ${num(spec.lambda0)},
    scale: ${num(fit.scale)},
    dx: ${num(fit.dx)},
    dy: ${num(fit.dy)},
  }`;

const out = `/* Generated by scripts/build-us-atlas.mjs — Albers insets for the lower 48, Alaska, and Hawaii. */
export const US_ATLAS_WIDTH = ${WIDTH};
export const US_ATLAS_HEIGHT = ${HEIGHT};

export const US_INSET_FRAMES = [
  { name: "Alaska", x: ${AK_BOX.x0}, y: ${AK_BOX.y0}, width: ${AK_BOX.x1 - AK_BOX.x0}, height: ${AK_BOX.y1 - AK_BOX.y0} },
  { name: "Hawaii", x: ${HI_BOX.x0}, y: ${HI_BOX.y0}, width: ${HI_BOX.x1 - HI_BOX.x0}, height: ${HI_BOX.y1 - HI_BOX.y0} },
] as const;

type AlbersFit = {
  n: number;
  c: number;
  rho0: number;
  lambda0: number;
  scale: number;
  dx: number;
  dy: number;
};

const LOWER: AlbersFit = ${specLiteral(lowerSpec, lowerFit)};
const ALASKA: AlbersFit = ${specLiteral(akSpec, akFit)};
const HAWAII: AlbersFit = ${specLiteral(hiSpec, hiFit)};

const DEG = Math.PI / 180;

function projectWith(lat: number, lng: number, spec: AlbersFit) {
  const phi = lat * DEG;
  const lambda = lng * DEG;
  const rho = Math.sqrt(spec.c - 2 * spec.n * Math.sin(phi)) / spec.n;
  const theta = spec.n * (lambda - spec.lambda0);
  const x = rho * Math.sin(theta);
  const y = -(spec.rho0 - rho * Math.cos(theta));
  return { x: x * spec.scale + spec.dx, y: y * spec.scale + spec.dy };
}

/** Map a WGS84 point onto the United States atlas, including Alaska and Hawaii insets. */
export function projectUs(lat: number, lng: number) {
  if (lat > 50 && lng < -130) return projectWith(lat, lng, ALASKA);
  if (lat < 23.5 && lng < -140) return projectWith(lat, lng, HAWAII);
  return projectWith(lat, lng, LOWER);
}

export const US_STATE_SHAPES: { name: string; d: string }[] = [
${shapes.map((s) => `  { name: ${JSON.stringify(s.name)}, d: ${JSON.stringify(s.d)} },`).join("\n")}
];
`;

writeFileSync(new URL("../src/lib/us-atlas.ts", import.meta.url), out);

function projectWithInline(lat, lng, spec, fit) {
  return applyFit(projectRaw(lat, lng, spec), fit);
}

