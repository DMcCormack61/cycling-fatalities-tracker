/**
 * Static country centers for filings that name a country but no mappable town.
 * Keys are already normalized (lowercase, accents stripped, punctuation to spaces).
 * Zoom is 5 for very large countries and 6 otherwise — a country view, not a site.
 */

export type CountryCenter = {
  latitude: number;
  longitude: number;
  zoom: 5 | 6;
};

export function normalizePlaceName(value: string): string {
  return value
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .replace(/\s+/g, " ");
}

